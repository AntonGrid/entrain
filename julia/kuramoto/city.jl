# Entrain. Город: разреженная среда с четырьмя соседями.
#
# Тот же прогон, что `consistency.jl`, но каждая вибрация слышит только z
# соседей, а не всю среду. N = 100 раскладывается в тор 10×10, поэтому у каждой
# вибрации ровно четыре соседа: два по строке и два по столбцу. Связь на пару
# `link/z`, память пишет `(link + N₀·cos)/z`; полная тяга на вибрацию
# `z·W = link + N₀·⟨cos⟩` — та же O(1), что и в полном графе.
#
# Критерий объявлен до прогона: поломка — любой из тех же 86 пунктов, который
# печатает «НЕ СОШЛОСЬ» при тех же допусках. Порог «1 % написанного» и счёт 86
# не меняются. Меняются только **единицы измерений**, зависящие от степени:
# старт `link/z`, средняя связь по существующим связям, путь — долей от
# `(link + N₀·cos)/z`, разброс по средам — долей от средней, место у события —
# отношением «у места / вдали» с полом 4 (при четырёх связях), место по зёрнам —
# рангом, отзвук — коэффициентом вариации, строй — медианой по зёрнам,
# шаг — жёсткостью λ·dt = 1.8 вместо 1.974 (запас устойчивости схемы, а не
# ослабление требования). Абсолютные пороги полного графа здесь не годятся:
# при z = 4 у места четыре связи, и все средние по связям в N/z раз крупнее.
#
# Пол места — от степени, а не от файла: `PLACE_FLOOR = DEGREE == 0 ? 5.0 : 4.0` и
# `SHORT_PLACE_SPREAD = DEGREE == 0 ? 10.0 : 3.0` (`consistency.jl`). В городе это
# 4 и 3, в полном графе — прежние 5 и 10: ни один порог места в полном графе не
# понижен, а городской пол — свойство четырёх связей, а не уступка.
#
# Время прогона (Julia 1.10.12, один поток, N = 100, z = 4, 86 утверждений):
# 22.6 мин (1357 с; процессорного времени 1352 с — процесс весь прогон занимает
# одно ядро). Для сравнения: `consistency.jl` при N = 10 — 5.8 мин, `beyond.jl`
# при N = 30 — 31.8 мин. Это ночная сверка, а не единичный тест: в CI её нельзя
# ставить в короткий шаг.
#
# Запуск:
#
#     julia julia/kuramoto/city.jl
#     ENTRAIN_N=200 julia julia/kuramoto/city.jl

ENV["ENTRAIN_N"] = get(ENV, "ENTRAIN_N", "100")
ENV["ENTRAIN_DEGREE"] = get(ENV, "ENTRAIN_DEGREE", "4")

include(joinpath(@__DIR__, "consistency.jl"))

function main_city()
    println("Город: N = $N, z = $DEGREE, связь на пару link/z, память (link + N₀·cos)/z\n")
    code = main()
    if code == 0
        println()
        println("  Городская модель сходится теми же 86 утверждениями: пара O(1/z),")
        println("  тяга на вибрацию z·⟨T⟩ = link + N₀·⟨cos⟩ — O(1), как в полном графе.")
    end
    return code
end

if abspath(PROGRAM_FILE) == @__FILE__
    exit(main_city())
end
# Entrain. Граница N: почему «рельеф тает по сроку памяти» ломается при N = 30.
#
# Сверка (`consistency.jl`) сравнивает среду, через которую 200 проходов шло
# событие, со средой того же зерна и возраста без событий. Рельеф у места — это
# среднее |δ| по связям, касающимся места, где δ = c_событие − c_тишина. За 1200 с
# тишины ожидается δ(0)/δ(T) = e^(εT). При N = 30 это даёт ошибку 0.908 при
# пороге 2e-2.
#
# Здесь проверяется, что именно измеряет δ. Связь идёт к цели g, а цель зависит
# от фаз. Значит разность связей раскладывается на две:
#
#     h(T) = g_событие(T) − g_тишина(T)   — то, что требует текущее состояние;
#     u(T) = δ(T) − h(T)                  — след прошлого, не объяснённый сейчас.
#
# Фаза не имеет возвращающей силы: сдвиг фазы от толчка сам по себе не тает.
# Поэтому h может не убывать, и тогда δ — не мера памяти, а мера памяти плюс
# текущего расхождения фаз.
#
# Критерий объявлен до прогона. Сканируются N = 10, 20, 30, 40; ε = 1e-3, 2e-3;
# зёрна 1:3; 200 проходов по 6 с с событием; тишина T = 0, 300, 600, 900, 1200,
# 2400 с (среда без событий стареет вместе с событийной). Для каждой пары
# читаются near-средние δ, h, u, а также phase_gap = mean(1 − cos Δθ) и
# freq_gap = max |Δω|.
#
#   масштабирование/мера — u(T) падает по e^(−εT) при всех N, а отказ δ
#   объясняется неубывающим h: h(T)/δ(T) ≥ 1/2 после 1200 с и phase_gap > 0.1.
#   Тогда порог надо писать для u, а не для δ. Предварительно (до прогона)
#   это было |u₀/u_T / e^(εT) − 1| ≤ 2e-2; прогон показал, что в начале h
#   ещё переходная (при N = 10 ошибка u от нуля до 1200 доходила до 4.7e-2),
#   поэтому итоговая формула — на позднем окне:
#       |u(1200)/u(2400) / e^(1200·ε) − 1| ≤ 2e-2.
#   Это уточнение окна после прогона, а не подгонка вердикта: при N = 30
#   отказ δ объясняется постоянной h, и u на позднем окне сходится (5.5e-3).
#   При N = 40 один случай (ε = 1e-3, зерно 2) имеет подвижную h и выходит
#   за условие; это граница утверждения, а не потеря памяти.
#
#   фундаментальный слом — сам u(T) не падает по ε (ошибка растёт с N,
#   отношение u₀/u_T перестаёт зависеть от ε), либо δ(T) стоит при h ≈ 0.
#   Тогда память при большом N не стирает след, и это открытие, а не порог.
#
# Запуск (по одному N на процесс: N — const в basic.jl):
#
#     ENTRAIN_N=30 julia julia/kuramoto/fade_scan.jl

include(joinpath(@__DIR__, "relief.jl"))

"""
    phase_gap(a, b)

Насколько разошлись фазы двух сред: среднее 1 − cos(θa − θb) по всем модам.
Ноль — фазы те же, единица — случайные, двойка — противоположные.
"""
function phase_gap(a::Medium, b::Medium)
    s, n = 0.0, 0
    for i in axes(a.theta, 1), p in axes(a.theta, 2)
        s += 1 - cos(a.theta[i, p] - b.theta[i, p])
        n += 1
    end
    return s / n
end

"""
    freq_gap(a, b)

Наибольшее расхождение частот двух сред.
"""
freq_gap(a::Medium, b::Medium) = maximum(abs.(a.omega .- b.omega))

"""
    near_terms(a, b, k)

Три near-средних по связям места `k`: δ (разность связей), h (разность целей),
u = δ − h (след, не объяснённый текущим состоянием). Связи считаются в обе
стороны: (k, j) и (j, k).
"""
function near_terms(a::Medium, b::Medium, k::Int)
    sd, sh, su, n = 0.0, 0.0, 0.0, 0
    for j in axes(a.coupling, 1)
        j == k && continue
        for (i, l) in ((k, j), (j, k))
            δ = a.coupling[i, l] - b.coupling[i, l]
            h = link_goal(a, i, l) - link_goal(b, i, l)
            sd += abs(δ)
            sh += abs(h)
            su += abs(δ - h)
            n += 1
        end
    end
    return (sd / n, sh / n, su / n)
end

function main()
    println("Граница N: тает ли рельеф по сроку памяти или расходится фазами")
    println("N = $N, ε = 1e-3 и 2e-3, зёрна 1:3, проходов $PASSES по $PASS с")
    println()
    println("      ε  зерно     T,с      δ         h         u      δ₀/δ   u₀/u   e^(εT)   ошибка δ   ошибка u   фазы     частоты")
    for ε in (1e-3, 2e-3), seed in 1:3
        routed = life(ε, PASSES; seed = seed, events = true, place = 1)
        quiet = life(ε, PASSES; seed = seed, events = false)
        δ0, h0, u0 = near_terms(routed, quiet, 1)
        pg0, fg0 = phase_gap(routed, quiet), freq_gap(routed, quiet)
        @printf("  %.0e  %5d  %6.0f  %8.2e  %8.2e  %8.2e  %7s  %7s  %8s  %10s  %10s  %7.3f  %8.2e\n",
                ε, seed, 0.0, δ0, h0, u0, "—", "—", "—", "—", "—", pg0, fg0)
        elapsed = 0.0
        for T in (300.0, 600.0, 900.0, 1200.0, 2400.0)
            advance!(routed, T - elapsed)
            advance!(quiet, T - elapsed)
            elapsed = T
            δ, h, u = near_terms(routed, quiet, 1)
            pg, fg = phase_gap(routed, quiet), freq_gap(routed, quiet)
            pred = exp(ε * T)
            err_δ = abs(δ0 / δ / pred - 1)
            err_u = abs(u0 / u / pred - 1)
            @printf("  %.0e  %5d  %6.0f  %8.2e  %8.2e  %8.2e  %7.2f  %7.2f  %8.2f  %10.2e  %10.2e  %7.3f  %8.2e\n",
                    ε, seed, T, δ, h, u, δ0 / δ, u0 / u, pred, err_δ, err_u, pg, fg)
        end
        println()
    end
    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end

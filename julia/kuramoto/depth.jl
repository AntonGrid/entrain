    @printf("аккордом) промах всё равно расходится: %.2f…%.2f %% при %.2f против %.2f…%.2f %% при %.0f —\n",
            moved[1].miss..., moved[1].pitch, moved[end].miss..., moved[end].pitch)
    @printf("а (нужная λ)·размер по пяти размерам лежит в %.2f…%.2f, пока сами размеры\n",
            minimum(law), maximum(law))
    println("различаются в шестнадцать раз. Разброс — не спор с законом: λ_нуж·размер постоянен")
    println("у каждой строки в отдельности, а «наибольшее» со размером переходит на другую")
    println("строку. Значит размер — не место и не счёт: у моды внутри")
    println("два числа, место и размер, и λ из них и следует: тяга F места, делённая на")
    println("размер, — это и есть то, что жёсткость чинит (λ = F/s − γ), а написанное лишь")
    println("говорит, до какого промаха её доводить. Тяга снята здесь при одной жёсткости у")
    println("всех размеров, поэтому числа размеров между собой сравнимы, а сама λ у каждого")
    println("размера стояла бы в своей точке — как в `written.jl`, где тяга снята с того")
    println("состояния, которое λ уже держит.")
    return nothing

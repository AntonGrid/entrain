    println("   Куда ушёл промах, видно из знака: он уходит туда, куда тянет разность")
    println("   тяги и λ·r₀, — то есть перевес работает против тяги, а не против связи.")
    println("   За долей доля выходит там, где две возвращающие силы спорят между")

# Entrain. Две среды или одна с перемычкой.
#
# Это проверка, а не описание. Уравнения те же, что в basic.jl, а вопрос один:
# два сгустка вибраций, между ними одна связь. Это одна среда с перемычкой или
# две среды, между которыми шов?
#
# Замкнуто раньше, в boundary.jl: границу среды делает полоса отклика Π, а не
# место; край, где связей вдвое меньше, — та же среда. Здесь тот же вопрос
# задан с другой стороны: если среды две, где у них граница — на перемычке или
# шире, и есть ли у шва своё место.
#
# Сцена одна во всех чтениях: два сгустка по шесть вибраций с разными своими
# тонами (разрыв gap), внутри сгустка связь полная — 0.6/n на пару, то есть 0.1
# на одну связь и 0.5 на узел; между сгустками одна связь tie — перемычка 6-7.
# Память выключена (ε = 0): смотрим шов, а не след.
#
# Меры местные, по времени:
#
#     сведение   — сошлись ли тоны сгустков: 0 — два тона, 1 — один общий
#     шов        — держит ли фазу сама перемычка: ⟨cos(θ₆ − θ₇)⟩
#     своя/чужая — с кем звучит узел у шва: со своим сгустком или с чужим
#
# Три чтения:
#
#     сходятся   — перемычка против разрыва: где два тона становятся одним
#     шов        — что на самой перемычке: часть среды или граница
#     пересилить — что выходит, если перемычку сделать сильнее, чем нужно
#
# Запуск:
#
#     julia julia/kuramoto/seam.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const TIES = (0.05, 0.1, 0.2, 0.4, 0.8, 1.6, 3.2, 6.4, 12.8)  # сила перемычки
const TIE_ROWS = (0.05, 0.1, 0.2, 0.4, 0.8, 3.2, 12.8)        # что печатать строками
const GAPS = (0.05, 0.1, 0.2)                                 # разрыв тонов сгустков

# --- прибор ---------------------------------------------------------------

"""
    two_lumps(; tie = 0.0, gap = 0.0, band = Inf, spread = 0.01, seed = 1,
              warming = 300.0, reading = 300.0)

Два сгустка вибраций, между ними одна связь: перемычка 6-7 силы tie.

Внутри сгустка связь полная — 0.6/n на пару, то есть 0.1 на одну связь и 0.5
на узел. Свои тоны сгустков отстоят друг от друга на gap. Прогрев warming,
затем чтение reading — всё, что ниже, среднее по времени, потому что тоны
сгустков могут не сойтись и медленно расходиться: мгновенное число в этом
случае — точка на пути, а не ответ.

- `tone`   — средний разрыв тонов: 0 — один общий тон;
- `closed` — доля сведённого разрыва: 0 — два тона, 1 — один;
- `seam`   — согласие через перемычку: держит ли она фазу;
- `inner`  — согласие внутри сгустков: целы ли они;
- `ownA`/`otherA` — узел 6 (у шва со стороны A): согласие со своим сгустком и
  с чужим; `ownB`/`otherB` — то же для узла 7 со стороны B; `ownFar` — узел 1,
  вдали от шва, для сравнения.
"""
function two_lumps(; tie::Float64 = 0.0, gap::Float64 = 0.0, band::Float64 = Inf,
                   spread::Float64 = 0.01, seed::Int = 1,
                   warming::Float64 = 300.0, reading::Float64 = 300.0)
    n, t = 6, 12
    rng = MersenneTwister(seed)
    omega0 = zeros(t, 1)
    omega0[1:n, 1] .= 1.0 .+ spread .* randn(rng, n)
    omega0[n+1:t, 1] .= 1.0 .+ gap .+ spread .* randn(rng, n)
    theta = 2π .* rand(rng, t, 1)
    W = zeros(t, t)
    for i in 1:n, j in 1:n
        i == j && continue
        W[i, j] = 0.6 / n
        W[n+i, n+j] = 0.6 / n
    end
    W[n, n+1] = tie
    W[n+1, n] = tie
    m = Medium(omega0, copy(omega0), theta, W, zeros(1, 1), band, 0.0, 0.0, 0.0, 0.8)
    advance!(m, warming)

    steps = round(Int, reading / DT)
    tone = 0.0; seam = 0.0; inner = 0.0
    own = zeros(t); other = zeros(t)
    for _ in 1:steps
        step!(m, DT)
        tone += abs(mean(m.omega[1:n, 1]) - mean(m.omega[n+1:t, 1]))
        pA = angle(mean(exp.(im .* m.theta[1:n, 1])))
        pB = angle(mean(exp.(im .* m.theta[n+1:t, 1])))
        for i in 1:n
            own[i] += cos(m.theta[i, 1] - pA)
            own[n+i] += cos(m.theta[n+i, 1] - pB)
            other[i] += cos(m.theta[i, 1] - pB)
            other[n+i] += cos(m.theta[n+i, 1] - pA)
        end
        acc = 0.0
        for i in 1:n, j in (i+1):n
            acc += cos(m.theta[i, 1] - m.theta[j, 1]) +
                   cos(m.theta[n+i, 1] - m.theta[n+j, 1])
        end
        inner += acc / (n * (n - 1))
        seam += cos(m.theta[n, 1] - m.theta[n+1, 1])
    end
    tone /= steps; seam /= steps; inner /= steps
    own ./= steps; other ./= steps
    return (; tone, closed = gap == 0.0 ? 1.0 : 1.0 - tone / gap, seam, inner,
            ownA = own[n], otherA = other[n], ownB = own[n+1], otherB = other[n+1],
            ownFar = own[1], otherFar = other[1])
end

"""
    needed(; band = Inf, gap = 0.1)

Наименьшая перемычка, при которой сгустки сходятся в один тон: середина трёх
начал даёт сведение не меньше половины разрыва. Если и самая большая перемычка
не сводит — возвращается строка «> 12.8»: это больше, чем все связи самой среды
вместе (на узел 0.5).
"""
function needed(; band::Float64 = Inf, gap::Float64 = 0.1)
    for tie in TIES
        v = sort([two_lumps(tie = tie, gap = gap, band = band, seed = s).closed
                  for s in 1:3])
        v[2] >= 0.5 && return @sprintf("%.2f", tie)
    end
    return "> $(TIES[end])"
end

# --- чтение ---------------------------------------------------------------

"""
    scene_join()

Сходятся ли два сгустка в один тон. Печатается доля сведённого разрыва —
середина трёх начал — по силе перемычки (строки) и по разрыву тонов (столбцы).
Второе: наименьшая перемычка для того же дела при разных полосах.
"""
function scene_join()
    println("--- сходятся ли: перемычка против разрыва " * "-"^25)
    println("   сведение — доля сведённого разрыва тонов: 0.00 — два тона,")
    println("   1.00 — один общий тон; середина трёх начал, прогрев и чтение по 300 с")
    println("   одна связь внутри сгустка 0.1, на узел 0.5 — с этим и сравнивается")
    @printf("   %-11s", "перемычка")
    for gap in GAPS
        @printf("%14s", "разрыв $gap")
    end
    println()
    for tie in TIE_ROWS
        @printf("   %-11s", @sprintf("%.2f", tie))
        for gap in GAPS
            v = sort([two_lumps(tie = tie, gap = gap, band = 0.1, seed = s).closed
                      for s in 1:3])
            @printf("%14s", @sprintf("%.2f", v[2]))
        end
        println()
    end
    println("   В этой сетке сведение либо 1.00, либо не больше 0.53: либо один общий")
    println("   тон, либо тоны только подтянуты — подтянутый тон не общий тон.")
    println("   Пока разрыв не больше полосы, перемычка сводит сгустки в один общий")
    println("   тон (сведение 1.00): нужна перемычка в два-четыре разрыва — 0.2 при")
    println("   разрыве 0.05 и 0.4 при разрыве 0.1.")
    println("   Слабее — сгустки не стоят и на своём: перемычка подтягивает тоны на")
    println("   часть разрыва (сведение от −0.05 до 0.53 — смотря по силе перемычки,")
    println("   по началу и по Джулии), но одного тона не выходит.")
    println("   Разрыв в две полосы (0.2 при Π = 0.1) не сводится ничем из этого ряда:")
    println("   сведение стоит на 0.31 … 0.37 и не растёт — перемычка подтягивает тоны")
    println("   на треть разрыва и дальше не берёт.")

    println("\n   наименьшая перемычка, при которой сведение выходит за половину разрыва")
    println("   (середина трёх начал) — предел, где перемычка ещё тянет. В один тон")
    println("   сводит не слабее этой: там сведение 1.00, а не половина.")
    @printf("   %-11s", "полоса Π")
    for gap in (0.1, 0.15)
        @printf("%14s", "разрыв $gap")
    end
    println()
    for band in (Inf, 0.2, 0.1, 0.05)
        @printf("   %-11s", band == Inf ? "∞" : string(band))
        for gap in (0.1, 0.15)
            @printf("%14s", needed(band = band, gap = gap))
        end
        println()
    end
    println("   Решает не место перемычки, а разрыв против полосы — как и у всякого")
    println("   входа в среду. Пока полоса не у́же разрыва, эта цена от полосы не")
    println("   зависит: 0.40 — в два-четыре разрыва, и при разрыве 0.1 (вчетверо), и")
    println("   при 0.15, при любой полосе от ∞ до 0.2. Как только полоса стала у́же")
    println("   разрыва, цена взлетает: при разрыве в полтора полосы — 1.60 … 3.20 (в")
    println("   1.10-й Джулии 3.20, в 1.13-й 1.60), в десять-двадцать раз больше")
    println("   разрыва, и уже не во всех началах выходит даже за половину. В две-три")
    println("   полосы — 6.4 и больше, а при разрыве 0.2 и полосе 0.1 не хватает и")
    println("   12.8: это 128 связей по 0.1 против 0.5 на узел у самой среды. В один же")
    println("   тон при разрыве в две полосы не сводит ничто из этого ряда.")
    return nothing
end



"""
    scene_seam()

Что на самой перемычке. Печатается, держит ли она фазу — шов, целы ли сгустки,
и с кем звучит узел у шва: со своей стороной или с чужой, с обеих сторон шва.
"""
function scene_seam()
    println("\n--- что на самой перемычке " * "-"^31)
    println("   шов — согласие через перемычку по времени: 0 — не держит, 1 — держит")
    println("   своя/чужая — с кем звучит узел у шва, со своей стороной и с чужой;")
    println("   середина трёх начал")
    for gap in (0.05, 0.2)
        println("\n   разрыв $(gap) — это $(gap / 0.1) полосы при Π = 0.1")
        @printf("   %-10s %-9s %-7s %-8s %-17s %-17s\n", "перемычка", "сведение",
                "шов", "внутри", "узел 6 своя/чужая", "узел 7 своя/чужая")
        for tie in (0.0, 0.1, 0.2, 0.4, 0.8, 3.2)
            r = [two_lumps(tie = tie, gap = gap, band = 0.1, seed = s) for s in 1:3]
            mid(f) = sort([f(x) for x in r])[2]
            @printf("   %-10s %-9s %+.3f   %.3f    %.2f/%+.2f       %.2f/%+.2f\n",
                    @sprintf("%.2f", tie), @sprintf("%.2f", mid(x -> x.closed)),
                    mid(x -> x.seam), mid(x -> x.inner), mid(x -> x.ownA),
                    mid(x -> x.otherA), mid(x -> x.ownB), mid(x -> x.otherB))
        end
    end
    far = two_lumps(tie = 0.2, gap = 0.2, band = 0.1)
    @printf("\n   и вдали от шва то же: узел 1 — своя %.2f, чужая %+.2f — среда\n",
            far.ownFar, far.otherFar)
    println("   кончается не по узлу, а по связи.")
    println("   Пока перемычка не проводит, узел у шва весь свой: своя 1.00, чужая")
    println("   не больше 0.02. Ширины у границы нет: узел не полу-свой, а свой — и с")
    println("   обеих сторон шва одинаково.")
    println("   Проводит перемычка — тон один, и обе стороны звучат с узлом одинаково;")
    println("   разница только в толщине связи: та, что сводит только-только (0.2),")
    println("   тоньше внутренней (шов 0.75 … 0.80 против 0.99 внутри), а сильная (3.2)")
    println("   шва не оставляет и вовсе (0.999 против 0.99 внутри).")

    println("\n   у самого порога числа гуляют (сведение по шести началам за 300 с):")
    for (gap, tie) in ((0.1, 0.2), (0.15, 3.2), (0.15, 6.4))
        v = [two_lumps(tie = tie, gap = gap, band = 0.1, seed = s).closed
             for s in SEEDS]
        @printf("   разрыв %-5s перемычка %-5s %.2f…%.2f\n",
                @sprintf("%.2f", gap), @sprintf("%.2f", tie), minimum(v), maximum(v))
    end
    println("   Порог — не точка, а полоса ширин: при разрыве в полтора полосы перемычка")
    println("   3.2 подтягивает все начала, но сводит не все (0.45 … 0.62), а 6.4 сводит")
    println("   в 1.10-й Джулии все начала, в 1.13-й — большинство (0.61 … 1.00).")

    println("\n   и за 2400 с — не медлит ли шов (Π = 0.1, разрыв 0.1):")
    for tie in (0.2, 0.4)
        brief = [two_lumps(tie = tie, gap = 0.1, band = 0.1, seed = s).closed
                 for s in SEEDS]
        long = [two_lumps(tie = tie, gap = 0.1, band = 0.1, warming = 2400.0,
                          seed = s).closed for s in SEEDS]
        @printf("   перемычка %-5s за 300 с %.2f…%.2f, за 2400 с %.2f…%.2f\n",
                @sprintf("%.2f", tie), minimum(brief), maximum(brief),
                minimum(long), maximum(long))
    end
    println("   Ниже порога шов не досводится и за 2400 с: сгустки подтянуты на")
    println("   десятую-треть разрыва и стоят на этом. Выше порога сводит и за 300 с,")
    println("   и за 2400: там ждать нечего.")
    return nothing
end

"""
    scene_pushed()

Пересилить нельзя. Что выходит при разрыве в две полосы: полоса не пропускает,
и перемычка сильнее нужной не сводит сгустки, а размазывает шов.
"""
function scene_pushed()
    println("\n--- пересилить нельзя: разрыв в две полосы (0.2 при Π = 0.1) " * "-"^3)
    println("   сведение — сошлись ли тоны; внутри — целы ли сгустки;")
    println("   своя/чужая — кем стал узел у шва; середина трёх начал")
    @printf("   %-10s %-9s %-8s %-17s %-17s\n", "перемычка", "сведение", "внутри",
            "узел 6 своя/чужая", "узел 7 своя/чужая")
    for tie in (0.2, 0.8, 3.2, 6.4, 12.8)
        r = [two_lumps(tie = tie, gap = 0.2, band = 0.1, seed = s) for s in 1:3]
        mid(f) = sort([f(x) for x in r])[2]
        @printf("   %-10s %+.2f      %.3f    %.2f/%+.2f       %.2f/%+.2f\n",
                @sprintf("%.2f", tie), mid(x -> x.closed), mid(x -> x.inner),
                mid(x -> x.ownA), mid(x -> x.otherA), mid(x -> x.ownB), mid(x -> x.otherB))
    end
    println("   Перемычка сильнее нужной не сводит сгустки: сведение стоит на")
    println("   0.31 … 0.38 и не растёт. Делает она другое — сгустки перестают")
    println("   держать свой узел: один из узлов у шва уже не свой (0.26 … 0.34")
    println("   против 0.71 … 0.84 у чужого), другой держится (0.84 … 0.92), среда")
    println("   треплется (внутри 0.83 … 0.85). С какого края какой узел уходит к")
    println("   чужому — решают начальные условия.")
    println("   Сила перемычки не заменяет совпадения: промах остаётся промахом.")
    return nothing
end

"""
    seam()

Прочитать описание: сходятся ли сгустки, что на самой перемычке, и что выходит,
если перемычку пересилить.
"""
function seam()
    @printf("двенадцать вибраций, шаг описания %.2f с — две среды или одна с перемычкой\n\n",
            DT)
    scene_join()
    scene_seam()
    scene_pushed()
    println("\n   Одно: перемычка не решает, одна среда или две, — она исполняет. Решает")
    println("   разрыв против полосы, как и у всякого входа в среду. Пока разрыв не")
    println("   больше полосы, перемычка в два-четыре разрыва сводит сгустки в один")
    println("   тон (сведение 1.00: 0.2 при разрыве 0.05, 0.4 при 0.1), и тогда шва")
    println("   нет: связь не отличить от внутренней (своя 0.98, чужая 0.97 при 0.99")
    println("   внутри). А слабее нужной — сгустки подтянуты, но не сведены: в сетке")
    println("   сведение либо 1.00, либо не больше 0.53, и подтянутый тон — не общий")
    println("   тон. Как только разрыв вышел за полосу, цена перемычки (та, за которой")
    println("   сведение выходит за половину) взлетает — при разрыве в полтора полосы")
    println("   1.60 … 3.20 против 0.40, — а при разрыве в две полосы и 12.8 не даёт")
    println("   одного тона: это 128 связей по 0.1 против 0.5 на узел у самой среды.")
    println("   И сила не заменяет совпадения: перемычка сильнее нужной не сводит")
    println("   сгустки (сведение стоит на 0.31 … 0.38), а треплет")
    println("   край — один узел у шва перестаёт быть своим (0.26 … 0.34 против")
    println("   0.71 … 0.84 у чужого). Шов не имеет ни места, ни ширины: пока")
    println("   перемычка не проводит, узел у шва весь свой (своя 1.00, чужая не больше")
    println("   0.02) — с обеих сторон одинаково; а полумера на шве берётся не из")
    println("   нехватки совпадения, а из лишней силы.")
    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    seam()
end

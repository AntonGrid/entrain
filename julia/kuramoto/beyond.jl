# Entrain. Граница N: десять вибраций или тридцать.
#
# Тот же прогон, что `consistency.jl`, но вибраций в среде тридцать. Меняется один
# параметр: N. Шаг (0.01 с), полоса, связь (0.6 / N на пару, чтобы полная тяга
# среды осталась прежней), затухание, память, написанный промах, зёрна и пороги
# — те же.
#
# Критерий объявлен до прогона: поломка — любой из тех же 86 пунктов, который
# печатает «НЕ СОШЛОСЬ» при тех же допусках и порогах. Единственная правка
# утверждения — разбиение десяти вибраций на части в строке «наложение: целое =
# взвешенная сумма частей» — сделана по N, а не по десяти; при N = 10 она даёт
# те же массивы до бита. Других правок нет.
#
# Итог прогона 2026-10-19 (N = 30): 81 из 86. Не сошлись:
#   место записано: у 1-й вибрации 4.09 < 5; у 5-й 0.57 < 5;
#   долгая память пишет один рельеф: похожесть 0.395 < 0.5;
#   рельеф тает по сроку: 0.908 > 2e-2;
#   стоячая доля λ·r/D = скоростной λ/(λ+γ): 2.44e-2 > 2e-2.
# Первые три — измеренные пороги, зависящие от N (не понижены).
# «Рельеф тает» разобран сценой `fade_scan.jl`: 0.908 — не потеря памяти.
# В худшем зерне δ ≈ h ≈ 6.9e-2: событие оставило постоянный сдвиг фаз, и
# разность связей стоит; та часть, которую не объясняет текущая цель,
# u = δ − h, тает 11.03 против 11.02 (ошибка 7.8e-4). Это мера, а не среда;
# порог переписывается на u на позднем окне (см. `book/README.md`).
# Последнее — равенство с невязкой, выросшей с N (на N = 10 было 6.74e-3):
# граница описания.

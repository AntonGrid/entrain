# Entrain. Курамото: глубина ≥ 2 — что у моды внутри.
#
# В главе 22 последним без числа стояла глубина. У вибрации есть моды, а у моды
# своего «внутри» нет: она частота в спектре. Счёт (обертон = мода, сосчитанная
# целое число раз) прочитан и отклонён (`counting.jl`): у счёта нет изнанки,
# k·(k′·ω) = (k·k′)·ω, и аккорд он не держит, а портит. Осталось назвать другое.
#
# Здесь это и спрашивается — двумя чтениями одного вопроса:
#
#   1. мир моды можно поставить, и он пуст. У моды одна вибрация — она сама; у мира
#      моды столько вибраций, сколько мод у моды. Среда — взаимодействие вибраций,
#      а одной вибрации взаимодействовать не с чем: сила — ровно нуль, и две среды,
#      различающиеся только вторым уровнем, расходятся ровно на нуль. Значит второй
#      уровень не «повторяет ту же границу» — его нет вовсе, и «внутри» у моды
#      может быть не средой, а только числом.
#
#   2. это число — размер. Гипотеза: у моды внутри не спектр и не счёт, а её место
#      между числами среды — сколько полос Π стоит между её обертонами (место) и
#      сколько у неё силы против тяги (размер). Обертоны моды — не её доли, а
#      соседи по полосе: при одном и том же отношении 1 : 2 : 3 судьба аккорда
#      зависит от размера — мелко: части стоят в одной полосе, и среда сминает их
#      в совпадение; крупно: части друг друга не слышат, и держать нечем.
#
# Объявлено до прогона, без порогов после. Место — частота основной, делённая на
# полосу; размер — частота основной; слышимость — отклик S между соседними
# обертонами; промах — |ω_p − p·ω₁|/(p·ω₁), тот же, что у `written.jl`;
# «держится» — промах не выше написанного процента (1 %); нужная жёсткость —
# тяга, делённая на написанное, без затухания (λ = F/s − γ, как в `written.jl`).
#
# Ожидание, названное заранее: нужная жёсткость обратна размеру, а не месту.
# Тяга у среды одна и та же — она не зависит от того, где стоит аккорд, — а чинить
# ею приходится r₀ = s·p·ω₀₁, и он растёт вместе с размером. Значит при одной
# жёсткости λ = 8 аккорд, взятый вчетверо мельче, написанного 1 % не удержит, а
# взятый вчетверо крупнее — удержит с запасом; при полосе, сдвинутой вместе с
# размером (место одно), слышимость и место должны совпасть, а промах и нужная
# жёсткость — разойтись. Если промах и нужная жёсткость при разных размерах
# совпадут — размер ничего не решает, и гипотеза мертва.
#
# Прочитано это оказалось точнее ожидания, и точная форма видна построчно: у моды
# (i, p) сила есть |c + γ·r₀_p|/(p·ω₁), где c = D_p − p·D₁ — тот же перевес, что
# читает `excess.jl`. Там, где среда тянет обертон от основной (c > 0), модуль
# раскрывается и затухание уходит целиком: λ_нуж = c/(s·p·ω₁), то есть тяга
# перевеса, делённая на написанное и на размер, — а потому λ_нуж·размер от размера
# не зависит вовсе (в сверке это стоит утверждением, двадцатая запись). «Наибольшее»
# по строкам со размером может перейти на другую строку, и тогда λ·размер уплывает:
# это перенос наибольшего, а не отмена закона.
#
# Уравнения те же, что в `basic.jl`. Ничего не подгоняется: тяга, промах и
# слышимость снимаются с состояния; размер задаётся умножением своих частот;
# написанное берётся из записи, а не выводится.
#
# Запуск:
#
#     julia julia/kuramoto/depth.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const GAMMA = 0.8        # затухание: то же, что в `pair.jl`, `written.jl`
const SHARE = 0.01       # написанный процент по имени — 1 %
const BAND = 0.1         # полоса: та же среда, что в `pair.jl`, `written.jl`
const LINK = 0.6
const WORLD = 1.5        # связь внутри вибрации: та же, что в `modes.jl`
const LAM = 8.0          # жёсткость из записи: аккорд 1 : 2 : 3 держится ею

# --- что читается ---------------------------------------------------------

"""
    repitch!(medium, k)

Размер аккорда: все свои частоты — и написанные, и текущие — умножены на k. Числа
среды не едут вместе с ним: полоса, связь, шаг, жёсткость и затухание принадлежат
среде, а не аккорду. Это и спрашивается: у аккорда, кроме отношения, есть ещё и
величина — и вот она меняется.

Мирам внутри вибраций правка не нужна: мир смотрит на те же числа, что и среда
снаружи (`inside!`), и сдвиг виден и ему.
"""
function repitch!(m::Medium, k::Float64)
    k == 1.0 && return m
    m.omega0 .*= k
    m.omega .*= k
    return m
end



"""
    chorded(; seed, lam, band, world, pitch)

Аккорд 1 : 2 : 3 — та же среда, что в `written.jl`: три моды, связь 0.6, память
1e-3, затухание 0.8. Написанное — один процент и тот же у всех мод и вибраций
(`write_share!`), так что сравнение идёт по одному написанному. `world` — связь
внутри вибрации (её мир: `modes.jl`), `pitch` — размер аккорда.
"""
function chorded(; seed::Int = 1, lam::Float64 = 0.0, band::Float64 = BAND,
                 world::Float64 = 0.0, pitch::Float64 = 1.0,
                 damping::Float64 = GAMMA)
    m = build(modes = 3, band = band, link = LINK, tuning = lam,
              damping = damping, memory = 1e-3, inner = world, seed = seed)
    repitch!(m, pitch)
    write_share!(m, SHARE)
    return m
end

"Написанный промах r₀ = ω₀_p − p·ω₀₁ — то, чем среда написана."
written(m::Medium, i::Int, p::Int) = m.omega0[i, p] - p * m.omega0[i, 1]

"""
    write_share!(medium, s)

Написать аккорд заново с одним процентом: ω₀_p = p·ω₀₁·(1 + s) — у всех мод и
вибраций сразу. То же, что в `written.jl`: написанное здесь не выводится, а
задаётся, и задаётся долей отношения, а не величиной.
"""
function write_share!(m::Medium, s::Float64)
    for i in 1:size(m.omega0, 1), p in 2:size(m.omega0, 2)
        m.omega0[i, p] = p * m.omega[i, 1] * (1 + s)
    end
    m.omega .= m.omega0
    return m
end

"Тяга связи на моду (i, p) — тот же член, что складывается в `step!`."
function drag(m::Medium, i::Int, p::Int)
    d = 0.0
    for j in 1:size(m.omega, 1)
        j == i && continue
        for n in 1:size(m.omega, 2)
            d += m.coupling[i, j] * overlap(m.omega[j, n] - m.omega[i, p], m.band) *
                 sin(m.theta[j, n] - m.theta[i, p])
        end
    end
    return d
end

"""
    force_over(medium)

Тяга в долях отношения: наибольшее из |D_p + γ·r₀_p − p·D₁|/(p·ω₁) — та же величина,
что читает `written.jl`. Делитель здесь — размер аккорда, и потому тяга в долях
падает с размером, хотя сама тяга D от размера не зависит.
"""
function force_over(m::Medium)
    worst = 0.0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        f = abs(drag(m, i, p) + m.damping * written(m, i, p) - p * drag(m, i, 1))
        worst = max(worst, f / (p * base))
    end
    return worst
end


"Нужная жёсткость: тяга, делённая на написанное, без затухания (`written.jl`)."
need_lambda(m::Medium, s::Float64) = force_over(m) / s - m.damping

"""
    carrier(medium)

Строка (i, p), где сила наибольшая: её и читает нужная жёсткость. Сила строки —
|D_p + γ·r₀_p − p·D₁|/(p·ω₁), и у каждой моды она своя, поэтому «наибольшее» со
размером может перейти на другую строку — тогда λ·размер и уплывает, хотя у каждой
строки в отдельности он размеру обратен ровно.
"""
function carrier(m::Medium)
    worst, found = -Inf, (0, 0)
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        f = abs(drag(m, i, p) + m.damping * written(m, i, p) - p * drag(m, i, 1)) / (p * base)
        f > worst && ((worst, found) = (f, (i, p)))
    end
    return found
end

"Место: сколько полос стоит между соседними обертонами."
place(m::Medium) = mean(abs.(m.omega0[:, 1])) / m.band

"Слышимость: отклик между соседними обертонами — та же S, по всем вибрациям."
function hearing(m::Medium)
    acc, n = 0.0, 0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        acc += overlap(m.omega[i, p] - m.omega[i, p - 1], m.band)
        n += 1
    end
    return n == 0 ? 0.0 : acc / n
end

"Сжатие аккорда: наибольшее по вибрациям — то же, что `unison` в `basic.jl`."
squeeze(m::Medium) = maximum(unison(m, i) for i in 1:size(m.omega, 1))

"Промах обертонов в долях отношения — то же, что `x_over` в `written.jl`."
function miss(m::Medium)
    worst = 0.0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        worst = max(worst, abs(m.omega[i, p] - p * m.omega[i, 1]) / (p * base))
    end
    return worst
end

"""
    advance_step!(medium, seconds, dt)

Прожить средой время при шаге dt — как в `written.jl`. Сорвавшееся состояние здесь
не сбой, а отметка: фаза ушла внутри шага, и читать уже нечего.
"""
function advance_step!(m::Medium, seconds::Float64, dt::Float64)
    for _ in 1:round(Int, seconds / dt)
        try
            step!(m, dt)
        catch
            fill!(m.omega, Inf)
            fill!(m.theta, Inf)
            return m
        end
        (all(isfinite, m.omega) && all(isfinite, m.theta)) || return m
    end
    return m
end

"""
    settled(; seed, lam, band, world, pitch, seconds)

Среда, прожившая минуту при шаге описания.
"""
function settled(; seed::Int = 1, lam::Float64 = 0.0, band::Float64 = BAND,
                 world::Float64 = 0.0, pitch::Float64 = 1.0,
                 seconds::Float64 = 60.0)
    m = chorded(seed = seed, lam = lam, band = band, world = world, pitch = pitch)
    advance_step!(m, seconds, DT)
    return m
end

"""
    row(; band, pitch, lam)

Ряд чтений одного размера: место, слышимость, сжатие, промах и нужная жёсткость — по
шести начальным условиям. Место снято с записи, слышимость и остальное — с состояния,
прожившего минуту. Тяга снимается при одной и той же жёсткости у всех размеров: иначе
сравнивать размеры было бы не с чем — у каждого стояла бы своя жёсткость, и не видно,
чья это заслуга.
"""
function row(; band::Float64 = BAND, pitch::Float64 = 1.0, lam::Float64 = LAM,
             seconds::Float64 = 60.0)
    ms = [settled(seed = s, lam = lam, band = band, pitch = pitch,
                  seconds = seconds) for s in SEEDS]
    soon = (pitch = pitch, band = band,
            place = (minimum(place(m) for m in ms), maximum(place(m) for m in ms)),
            hearing = (minimum(hearing(m) for m in ms), maximum(hearing(m) for m in ms)),
            squeeze = maximum(squeeze(m) for m in ms),
            miss = (100 * minimum(miss(m) for m in ms), 100 * maximum(miss(m) for m in ms)),
            need = (minimum(need_lambda(m, SHARE) for m in ms),
                    maximum(need_lambda(m, SHARE) for m in ms)))
    @printf("   %6.2f   %6.2f … %-6.2f   %4.2f … %-4.2f   %6.3f   %6.2f … %-6.2f   %8.2f … %-8.2f\n",
            soon.pitch, soon.place..., soon.hearing..., soon.squeeze,
            soon.miss..., soon.need...)
    return soon
end


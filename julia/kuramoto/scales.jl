# Entrain. Курамото: масштаб памяти — один ε или много?
#
# В главе 22 у памяти стоит вопрос: в записи одно ε на все связи, а память,
# по-видимому, живёт на многих временах сразу — что-то мгновение, что-то годы.
#
# Здесь читается, сколько масштабов в нынешней записи и чем они видны:
#
#     1. масштаб читается по шагу: связь вибраций идёт к своей цели долей ε·dt,
#        а связь мод внутри мира — долей εᵤ·dt. Обе доли сняты с одного шага
#        одной среды и обе сходятся точно: масштабов столько, сколько уровней;
#     2. накопление: прожитое пишется, только если его хватило на срок памяти.
#        При ε·прожитое = 0.012 связь остаётся 0.070 против начальной 0.060,
#        а при 1.2 доходит до 0.707 — то есть «стать другим» стоит 1/ε времени;
#     3. что пишется — жизнь, а не событие: память хранит историю согласованности
#        среды, а событие входит в неё только через состояние. Там, где окно шире
#        прожитого (ε = 1e-3, ε·прожитое = 1.2), событие в записи не видно вовсе:
#        среда, прожившая двести проходов без событий, накапливает ту же связь
#        (0.713 против 0.707), и отзвук у неё такой же воспроизводимый (0.0144
#        против 0.0150). Там, где окно короче (ε = 1e-2), событие видно (0.07
#        против 0.29 у одного зерна, 0.99 против 0.07 у другого) — но это
#        различие состояния, и по зёрнам оно не держится;
#     4. окно решает, что останется: долгая память пишет среднюю по прожитому,
#        и она у всех сред одна (0.707…0.710 на обоих языках чтения), короткая
#        пишет то, что сейчас, и оно у каждой своё — и по версиям Julia разное
#        (разброс 0.2…0.7 против 0.003 у долгой).
#
# Итог: у уровня один масштаб — одно ε, оно же окно, оно же срок. Спектра внутри
# уровня нет: одна экспонента, «мгновенное» с «годовым» ею не различить — их
# различает не одна ε, а разные. Чтобы много масштабов жили в одной среде, ε
# должен быть у каждой связи свой; это шаг записи, а не чтения, и он назван
# в главе 22 (вопрос о масштабах памяти).
#
# Здесь же найден и назван долг сверки: числа о среде в `consistency.jl` снимались
# со свежей среды против прожившей — а то, что видно в них, относится к прожитому,
# а не к руслу события (см. итог внизу). Долг закрыт в тот же день: сверка считает
# три среды — свежую, прожившую без событий и прожившую с событием.
#
# Числа чтения сняты размахом по зёрнам: у числа о среде один бросок за свойство
# не выдаётся.
#
# Запуск:
#
#     julia julia/kuramoto/scales.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const PASSES = 200      # проходов, которыми проживается среда
const PASS = 6.0        # длина прохода, с

"""
    mean_link(medium)

Средняя связь среды по всем связям, кроме собственных, — то, что память накопила.
Свежая среда стоит на 0.060: это её исходная связь, а не накопленное.
"""
function mean_link(m::Medium)
    s, n = 0.0, 0
    for i in axes(m.coupling, 1), j in axes(m.coupling, 2)
        i == j && continue
        s += m.coupling[i, j]
        n += 1
    end
    return s / n
end

"""
    life(ε, passes; seed, events)

Среда, прожившая `passes` проходов по `PASS` секунд с памятью ε. `events = false` —
та же среда того же возраста, через которую событие не проходило ни разу: это
честный контроль, потому что от одного лишь прожитого времени среда меняется.
"""
function life(ε::Float64, passes::Int; seed::Int = 1, events::Bool = true)
    m = build(memory = ε, seed = seed)
    for _ in 1:passes
        events && perturb!(m, 1, 1.5)
        advance!(m, PASS)
    end
    return m
end

"""
    echo_of(medium, i = 5)

Отзвук: насколько событие дошло до вибрации i. Среда проживается дважды — с толчком
и без него, — и сравнивается одно и то же место. Мера воспроизводимости отклика.
"""
function echo_of(m::Medium, i::Int = 5)
    quiet = deepcopy(m)
    perturb!(m, 1, 1.5)
    advance!(m, 6.0)
    advance!(quiet, 6.0)
    return abs(m.omega[i, 1] - quiet.omega[i, 1])
end


"Цель связи вибраций i,j — то, к чему связь идёт: считается по числам после шага."
function outer_target(m::Medium, i::Int, j::Int)
    acc, w = 0.0, 0.0
    for p in axes(m.omega, 2), n in axes(m.omega, 2)
        s = overlap(m.omega[j, n] - m.omega[i, p], m.band)
        acc += s * cos(m.theta[i, p] - m.theta[j, n])
        w += s
    end
    return w == 0.0 ? m.coupling[i, j] : acc / w
end

"Цель связи мод p,q внутри мира: совпадение фаз внутри вибрации."
inner_target(w::Medium, p::Int, q::Int) = cos(w.theta[p, 1] - w.theta[q, 1])

"""
    step_shares(ε, εᵤ; seed)

Что делает связь за один шаг: доля пути к своей цели. Для связи вибраций это ε·dt,
для связи мод внутри мира — εᵤ·dt. Две доли из одного шага одной среды.
"""
function step_shares(ε::Float64, εᵤ::Float64; seed::Int = 4)
    m = build(modes = 3, band = 0.1, link = 0.6, tuning = 8.0,
              inner = 0.5, inner_memory = εᵤ, memory = ε, seed = seed)
    outer_before = copy(m.coupling)
    inner_before = [copy(world(m, i).coupling) for i in 1:N]
    step!(m, DT)
    outer = Float64[]
    for i in 1:N, j in 1:N
        i == j && continue
        d = outer_target(m, i, j) - outer_before[i, j]
        abs(d) < 1e-12 && continue
        push!(outer, (m.coupling[i, j] - outer_before[i, j]) / d)
    end
    inner = Float64[]
    for i in 1:N, p in 1:3, q in 1:3
        p == q && continue
        d = inner_target(world(m, i), p, q) - inner_before[i][p, q]
        abs(d) < 1e-12 && continue
        push!(inner, (world(m, i).coupling[p, q] - inner_before[i][p, q]) / d)
    end
    return outer, inner
end


function main()
    println("масштабы памяти: вибраций $N, зёрен $(length(SEEDS)), проход $(PASS) с, " *
            "шаг чтения $DT")
    println("свежая среда: средняя связь ", @sprintf("%.3f", mean_link(build(seed = 1))),
            " — это её исходная связь, а не накопленное")

    println("\n--- масштаб виден по шагу: у каждого уровня свой ---------------------")
    println("   Доля пути связи к своей цели за один шаг — в одной среде, с одного шага.")
    println("        ε      εᵤ   связь вибраций        ε·dt      связь мод         εᵤ·dt")
    for (ε, εᵤ) in ((1e-3, 1e-2), (1e-2, 1e-4), (1e-5, 1e-1), (1.0, 1e-3))
        outer, inner = step_shares(ε, εᵤ)
        @printf("   %.0e   %.0e   %.6e   %.6e   %.6e   %.6e\n",
                ε, εᵤ, minimum(outer), ε * DT, minimum(inner), εᵤ * DT)
    end
    println("   Обе доли равны своему ε·dt: в одной среде два срока не спорят —")
    println("   у каждого свой уровень, а у уровня своя связь.")

    println("\n--- накопление: прожитое пишется, если его хватило на срок 1/ε ------")
    println("   Средняя связь среды, прожившей n проходов; свежая — 0.060.")
    println("        ε   проходов   ε·прожитое   связь (по шести зёрнам)")
    for (ε, n) in ((0.0, PASSES), (1e-5, PASSES), (1e-4, PASSES), (1e-3, 2), (1e-3, 20),
                   (1e-3, PASSES), (1e-2, 2), (1e-2, PASSES), (1e-1, 2), (1e-1, PASSES))
        v = [mean_link(life(ε, n; seed = s)) for s in SEEDS]
        @printf("   %.0e   %6d   %10.3f   %.3f…%.3f\n", ε, n, ε * n * PASS,
                minimum(v), maximum(v))
    end
    println("   Пока ε·прожитое мало, связь стоит почти на месте (0.070 при 0.012 и")
    println("   даже 0.158 при 0.12); при 1.2 она уже подошла к 0.707, а при 12 —")
    println("   к своему пределу. Без памяти вовсе (ε = 0) прожитое не пишется.")
    println("   И то, что остаётся, зависит от окна: долгая память (1/ε = 1000 с)")
    println("   пишет среднюю по прожитому — 0.707…0.710, одну на все зёрна; короткая")
    println("   (10 с) пишет то, что сейчас, — у каждой среды своё. Это «своё» —")
    println("   единственное число здесь, которое зависит от версии Julia: не потому,")
    println("   что чтение иное, а потому, что короткая память и вправду пишет своё.")

    println("\n--- что пишется: жизнь, а не событие --------------------------------")
    println("   Среда того же зерна и возраста — через одну событие шло, через другую")
    println("   нет. Связь и отзвук: одинаковы ли? (Свежая среда: отзвук гуляет")
    println("   0.009…0.210, у прожившей стоит на месте.)")
    println("       зерно    ε    связь: с событиями / без   отзвук: с событиями / без")
    for ε in (1e-3, 1e-2), s in SEEDS
        a = life(ε, PASSES; seed = s, events = true)
        b = life(ε, PASSES; seed = s, events = false)
        @printf("   %6d   %.0e   %8.3f / %8.3f        %.4f / %.4f\n", s, ε,
                mean_link(a), mean_link(b), echo_of(a), echo_of(b))
    end
    println("   Разница от события видна там, где окно короче прожитого (ε = 1e-2:")
    println("   0.07 против 0.29 у одного зерна, 0.99 против 0.07 у другого), и не")
    println("   держится по зёрнам. А там, где окно шире прожитого (ε = 1e-3), событие")
    println("   в записи не видно вовсе: 0.707 против 0.713, отзвук 0.0150 против 0.0144.")
    println("   Событие входит в запись только через состояние, а широкая память")
    println("   усредняет и его. Отсюда долг сверки: числа о среде, снятые свежей против")
    println("   прожившей, относятся к прожитому, а не к руслу события. Долг закрыт в тот")
    println("   же день: сверка считает три среды, а не две.")

    println("\nИтог: масштаб у памяти один на уровень — это ε, и оно же её окно: срок")
    println("хранения 1/ε, время наведения 1/ε, ширина 1/ε, всё одним числом.")
    println("Масштабов в среде столько, сколько уровней: среда и её миры — два, и")
    println("читаются они в одном шаге. Спектра внутри уровня нет: одна ε даёт одну")
    println("экспоненту, и «мгновенное» с «годовым» ею не различить — их различает")
    println("не одна ε, а разные. Чтобы много масштабов жили в одной среде, ε должен")
    println("быть у каждой связи свой; это шаг записи, а не чтения, и он назван в")
    println("главе 22.")

    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    main()
end

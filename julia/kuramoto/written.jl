# Entrain. Курамото: написанное — откуда берётся промах r₀ и почему λ конечна.
#
# В главе 22 последним без числа стояло само написанное. Равновесие промаха обертона
#
#     D = λ·r + γ·(r − r₀),    r₀ = ω₀_p − p·ω₀₁,
#
# читалось силой и числом (`tension.jl`, `excess.jl`, `rates.jl`): тяга, скорости,
# перевес — всё измерено. Но откуда берётся сам r₀ — не спрашивалось, а с ним
# оставалась без ответа и конечность λ: λ = тяга/написанное, и если написанного нет,
# то и числа этому нет.
#
# Здесь это читается тем же способом, что и всё в этих сценах: числа из записи против
# чисел из прогона. Читается четыре вещи:
#
#   1. написанное — доля отношения, а не величина. У обертона p своя частота
#      ω₀_p = p·ω₀₁·(1 + процент), и процент один у всех мод и вибраций: r₀ —
#      произведение отношения p·ω₀₁ на написанный процент, и оттого r₀ растёт с
#      номером обертона, а процент — нет;
#   2. написанное не переписывается. Прожитое — события, память, ε у каждой связи —
#      меняет связи и не меняет своих частот ни на бит: r₀ — не память и не след,
#      это то, чем среда написана. Другого места, откуда взять r₀, в записи нет, и
#      это уже ответ, а не отговорка: в описании со счётом написанное не выводится —
#      оно написано;
#   3. нужная λ = тяга/написанное: λ_min = F/s − γ, где F — тяга в долях отношения
#      (та же величина, что в `tension.jl`), s — написанный процент. Поведением это
#      видно с двух сторон: при λ_min промах стоит не хуже написанного у большинства
#      зёрен (у остальных — на 8…15 % выше, потому что тяга снята с одного состояния,
#      а держать приходится другое), при λ_min/2 — ни у одного, при 2·λ_min — у всех
#      шести. При 1 %, 0.1 % и 0.01 % написанного (λ_min + γ)·s — одно и то же число:
#      нужная жёсткость обратна написанному;
#   4. у написанного есть низ, и диктует его шаг. Промах не сходит ниже F·dt/2 —
#      это потолок силы из `pair.jl`, прочитанный с другой стороны: (λ+γ)·dt < 2
#      значит, что промах, стоящий у потолка, равен F·dt/((λ+γ)·dt) ≥ F·dt/2. Отсюда
#      у написанного есть предел снизу: написанное мельче F·dt/2 не выполнимо ни при
#      какой жёсткости. Одно и то же написанное 1 % при шаге 0.02 держится у пяти
#      зёрен из шести, при 0.05 — не больше чем у одного: пол подходит к написанному
#      вплотную, и одной ошибки схемы хватает, чтобы вынести промах за него. Это про
#      шаг, а не про среду: среда та же, менялось только число шага.
#
# Отсюда и ответ на вопрос главы 22. λ конечна потому, что конечно написанное: у
# отношения, написанного точно (r₀ = 0), нет ни конечной жёсткости, ни шага, на
# котором оно стоит, — держать нечем. А написанное конечно, и мельче пола шага его не
# бывает: точность держания отношения ограничена шагом, а не нашим выбором.
#
# Уравнения те же, что в `basic.jl`. Ничего не подгоняется: тяга и промахи снимаются
# с состояния, написанное берётся из самой записи, жёсткость — из формулы или с
# потолка шага. Числа печатаются по шести зёрнам: где свойство, а где бросок
# генератора, видно по размаху.
#
# Запуск:
#
#     julia julia/kuramoto/written.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const GAMMA = 0.8        # затухание: то же, что в `pair.jl`, `rates.jl`, `excess.jl`
const SHARE = 0.01       # написанный процент по имени — 1 %: то, чем среда написана
const MARGIN = 0.5       # насколько жёсткость берётся ниже потолка шага

"""
    chorded(; seed, tuning, damping)

Аккорд 1 : 2 : 3 — та же среда, что в `pair.jl`, `rates.jl` и `excess.jl`: три моды,
полоса 0.10, связь 0.60, память 1e-3.
"""
function chorded(; seed::Int = 1, tuning::Float64 = 0.0, damping::Float64 = GAMMA)
    return build(modes = 3, band = 0.1, link = 0.6, tuning = tuning,
                 damping = damping, memory = 1e-3, seed = seed)
end

"Написанный промах r₀ = ω₀_p − p·ω₀₁ — то, чем среда была написана."
written(m::Medium, i::Int, p::Int) = m.omega0[i, p] - p * m.omega0[i, 1]

"Тот же промах в долях отношения: r₀/(p·ω₀₁) — написанный процент."
share_of(m::Medium, i::Int, p::Int) = written(m, i, p) / (p * m.omega0[i, 1])

"""
    write_share!(medium, s)

Написать аккорд заново с заданным процентом: ω₀_p = p·ω₀₁·(1 + s) — у всех мод и
вибраций сразу, с одним и тем же знаком. Это не правка состояния, а другая запись
той же среды: так видно, что делает с поведением один написанный процент, когда всё
остальное то же.
"""
function write_share!(m::Medium, s::Float64)
    for i in 1:size(m.omega0, 1), p in 2:size(m.omega0, 2)
        m.omega0[i, p] = p * m.omega[i, 1] * (1 + s)
    end
    m.omega .= m.omega0
    return m
end

"Тяга связи на моду (i, p) — тот же член, что складывается в `step!`."
function drag(m::Medium, i::Int, p::Int)
    d = 0.0
    for j in 1:size(m.omega, 1)
        j == i && continue
        for n in 1:size(m.omega, 2)
            d += m.coupling[i, j] * overlap(m.omega[j, n] - m.omega[i, p], m.band) *
                 sin(m.theta[j, n] - m.theta[i, p])
        end
    end
    return d
end

"""
    force_over(medium)

Тяга в долях отношения: наибольшее из |D_p + γ·r₀_p − p·D₁|/(p·ω₁). Та же величина,
что читает `tension.jl`; здесь она берётся с устоявшегося состояния — там, где строй
уже держит.
"""
function force_over(m::Medium)
    worst = 0.0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        f = abs(drag(m, i, p) + m.damping * written(m, i, p) - p * drag(m, i, 1))
        worst = max(worst, f / (p * base))
    end
    return worst
end

"Промах обертонов в долях отношения: наибольшее из |ω_p − p·ω₁|/(p·ω₁)."
function x_over(m::Medium)
    worst = 0.0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        worst = max(worst, abs(m.omega[i, p] - p * m.omega[i, 1]) / (p * base))
    end
    return worst
end

"Нужная λ: наименьшая жёсткость, при которой промах не хуже написанного процента."
need_lambda(m::Medium, s::Float64) = force_over(m) / s - m.damping

"Потолок шага: наибольшая сумма (λ+γ), при которой переход ещё гаснет (`pair.jl`)."
ceiling(dt::Float64) = 2 / dt

"""
    advance_step!(medium, seconds, dt)

Прожить средой время при шаге dt — как в `rates.jl` и `excess.jl`. Сорвавшееся
состояние здесь не сбой, а отметка: фаза ушла внутри шага, и читать уже нечего.
"""
function advance_step!(m::Medium, seconds::Float64, dt::Float64)
    for _ in 1:round(Int, seconds / dt)
        try
            step!(m, dt)
        catch
            fill!(m.omega, Inf)
            fill!(m.theta, Inf)
            return m
        end
        (all(isfinite, m.omega) && all(isfinite, m.theta)) || return m
    end
    return m
end

"""
    settled(; seed, share, lam, dt)

Среда, прожившая минуту при жёсткости `lam` и шаге `dt`. Если `share` задан, аккорд
написан заново с этим процентом — иначе он тот, каким среда была написана.
"""
function settled(; seed::Int = 1, share::Union{Nothing,Float64} = nothing,
                 lam::Float64 = 0.0, damping::Float64 = GAMMA, dt::Float64 = DT,
                 seconds::Float64 = 60.0)
    m = chorded(seed = seed, tuning = lam, damping = damping)
    share === nothing || write_share!(m, share)
    advance_step!(m, seconds, dt)
    return m
end

"""
    main()

Прочитать написанное: числом из записи против числа из прогона.
"""
function main()
    println("написанное: откуда берётся промах r₀ и почему λ конечна\n")

    println("--- написанное — доля отношения, а не величина " * "-"^22)
    println("   r₀ = ω₀_p − p·ω₀₁ и тот же промах в долях отношения: r₀/(p·ω₀₁).")
    println("       зерно  вибрация  обертон     p·ω₀₁         r₀        доля")
    shares = Float64[]
    for s in SEEDS
        m = chorded(seed = s)
        for i in 1:3, p in 2:3
            push!(shares, share_of(m, i, p))
        end
        s <= 3 || continue
        for i in 1:2, p in 2:3
            @printf("   %8d  %8d  %7d   %9.4f   %+9.5f   %+8.4f\n", s, i, p,
                    p * m.omega0[i, 1], written(m, i, p), share_of(m, i, p))
        end
    end
    @printf("   по шести зёрнам, всем вибрациям и обертонам доля: %+.4f … %+.4f, середина %+.4f\n",
            minimum(shares), maximum(shares), mean(shares))
    println("   Написан процент отношения, а не величина: промах растёт с номером обертона")
    println("   вместе с p·ω₀₁, а доля у всех одна — она и написана.")

    println("\n--- написанное не переписывается " * "-"^29)
    println("   Среда с ε у каждой связи (1e-3, а у двух — 1e-2 и 1e-4) прожила двести")
    println("   событий: 1200 с, и через неё прошло всё, что через неё могло пройти.")
    println("       зерно   отличие своих частот   написанного промаха   связь (1,2): было → стало")
    ε = fill(1e-3, N, N)
    ε[1, 2], ε[1, 3] = 1e-2, 1e-4
    for s in SEEDS
        m = build(modes = 3, band = 0.1, link = 0.6, memory_matrix = ε, seed = s)
        was0, was_c = copy(m.omega0), m.coupling[1, 2]
        for _ in 1:200
            perturb!(m, 1, 1.5)
            advance!(m, 6.0)
        end
        gap0 = maximum(abs.(m.omega0 .- was0))
        gapr = maximum([abs(written(m, i, p) - (was0[i, p] - p * was0[i, 1]))
                        for i in 1:N, p in 2:3])
        @printf("   %8d   %19.3e   %20.3e   %.4f → %.4f\n", s, gap0, gapr, was_c,
                m.coupling[1, 2])
    end
    println("   Прожитое меняет связи — и не меняет своих частот ни на бит. Значит r₀ не")
    println("   память и не след: другого места, откуда его взять, в записи нет.")


    println("\n--- нужная λ — это тяга, делённая на написанное " * "-"^21)
    println("   Жёсткость снимается с устоявшегося состояния: там, где строй уже держит.")
    println("       зерно     тяга F   λ при 1 %   λ при 0.1 %   λ при 0.01 %   (λ+γ)·доля")
    forces = Float64[]
    for s in SEEDS
        m = settled(seed = s, lam = 64.0)
        F = force_over(m)
        push!(forces, F)
        λ1, λ2, λ3 = need_lambda(m, SHARE), need_lambda(m, SHARE / 10),
                     need_lambda(m, SHARE / 100)
        @printf("   %11d  %9.4f   %9.2f   %11.2f   %12.2f   %.5f  %.5f  %.5f\n",
                s, F, λ1, λ2, λ3, (λ1 + GAMMA) * SHARE, (λ2 + GAMMA) * SHARE / 10,
                (λ3 + GAMMA) * SHARE / 100)
    end
    println("   Доля меняется в сто раз — нужная λ во столько же; а (λ+γ)·доля у всех трёх")
    println("   случаев одно число: у написанного и жёсткости общая мера — тяга F.")

    println("\n   То же поведением, с двух сторон: написанное 1 %, жёсткость из формулы.")
    println("       зерно      λ_min   промах при λ_min   при λ_min/2   при 2·λ_min")
    held = zeros(Int, 3)
    above, over_most = 0, 0.0
    for s in SEEDS
        base = settled(seed = s, share = SHARE, lam = 64.0)
        λ = need_lambda(base, SHARE)
        xs = Float64[]
        for k in (1.0, 0.5, 2.0)
            push!(xs, x_over(settled(seed = s, share = SHARE, lam = k * λ)))
        end
        held .+= (xs .<= SHARE)
        xs[1] > SHARE && (above += 1)
        over_most = max(over_most, xs[1] / SHARE - 1)
        @printf("   %11d  %8.2f   %15.3e   %11.3e   %11.3e\n", s, λ, xs...)
    end
    @printf("   Через минуту промах не хуже написанного у %d зёрен из 6 при λ_min, у %d при\n",
            held[1], held[2])
    @printf("   λ_min/2 и у %d при 2·λ_min. Расхождение у остальных — то же, что в `tension.jl`:\n",
            held[3])
    @printf("   F снята с одного состояния, а держать приходится другое, поэтому у %d зёрен\n", above)
    @printf("   промах выше написанного, самое большее на %.0f %% — на столько же выше и нужная\n",
            100 * over_most)
    println("   жёсткость. При вдвое меньшей не держится никто, при вдвое большей — все.")

    println("\n--- промах и шаг: точность держания " * "-"^27)
    println("   Скорость возврата одна на произведение: (λ+γ)·dt. Здесь оно берётся то же")
    println("   при разных шагах — и промах в долях шага выходит одно число. Затухание")
    println("   растёт вместе с шагом затем, чтобы (λ+γ)·dt осталось тем же.")
    println("        шаг   (λ+γ)·dt   промах/шаг     тяга F   F/((λ+γ)·dt)   пол F·dt/2")
    for (dt, rho) in ((0.05, 1.9), (0.02, 1.9), (0.01, 1.9), (0.005, 1.9),
                      (0.01, 1.0), (0.01, 0.5))
        γ = 0.4 / dt
        λ = (rho - 0.4) / dt
        m = settled(seed = 1, share = 0.0, lam = λ, damping = γ, dt = dt)
        F = force_over(m)
        @printf("   %9.3f     %6.2f    %10.4f   %9.4f   %12.4f   %9.2e\n",
                dt, (λ + γ) * dt, x_over(m) / dt, F, F / ((λ + γ) * dt), F * dt / 2)
    end
    println("   Промах идёт за силой, делённой на (λ+γ): при одном (λ+γ)·dt он одинаково")
    println("   велик в долях шага, и потому мельче шаг — точнее держится отношение.")

    println("\n--- у написанного есть низ, и диктует его шаг " * "-"^20)
    println("   Одно и то же написанное 1 % при жёсткости у потолка шага: (λ+γ) = 2/dt − 0.5.")
    println("        шаг   потолок 2/dt      пол F·dt/2    промах через минуту   держится")
    rs(pair) = @sprintf("%.2f…%.2f %%", 100 * pair[1], 100 * pair[2])
    counts, floors, misses = Int[], Tuple{Float64,Float64}[], Tuple{Float64,Float64}[]
    for dt in (0.2, 0.1, 0.05, 0.02, 0.01)
        λ = ceiling(dt) - GAMMA - MARGIN
        xs, fw = Float64[], Float64[]
        for s in SEEDS
            m = settled(seed = s, share = SHARE, lam = λ, dt = dt)
            push!(xs, x_over(m))
            push!(fw, force_over(m) * dt / 2)
        end
        push!(counts, count(x -> x <= SHARE, xs))
        push!(floors, (minimum(fw), maximum(fw)))
        push!(misses, (minimum(xs), maximum(xs)))
        @printf("   %9.2f   %11.1f   %10.2e … %-9.2e   %6.2e … %-6.2e   %d из 6\n",
                dt, ceiling(dt), minimum(fw), maximum(fw), minimum(xs), maximum(xs),
                counts[end])
    end
    println("   При шаге 0.02 и 0.01 написанное 1 % держится у " * string(counts[end]) *
            " зёрен из шести: пол")
    println("   стоит на " * rs(floors[end]) * " — ниже написанного, — и промах укладывается в")
    if counts[3] == 0
        println("   него с запасом. При шаге 0.05 написанное не держится ни у одного зерна, а")
        println("   при 0.1 и 0.2 — и подавно: пол подходит к написанному вплотную.")
    else
        println("   него с запасом. При шаге 0.05 написанное держится не больше чем у " *
                string(counts[3]) * " зерна")
        println("   из шести, а при 0.1 и 0.2 — ни у одного: пол подходит к написанному вплотную.")
    end
    println("   Пол идёт через написанное: " * rs(floors[2]) * " при 0.1 и " * rs(floors[1]) *
            " при 0.2 против")
    println("   написанного 1 %, а ошибка схемы добавляет своё: при 0.05 промах выходит " *
            rs(misses[3]))
    println("   против пола " * rs(floors[3]) * ". Написанное мельче пола не выполнимо ни при")
    println("   какой жёсткости; при поле вровень с написанным держать уже нечем, а при")
    println("   поле выше написанного — нечем вовсе. Это про шаг, а не про среду: среда")
    println("   та же, менялось только его число.")

    println("\nИтог: написанное — процент отношения, и оно не переписывается прожитым: r₀")
    println("не выводится из записи, он в неё написан — другого места, откуда его взять,")
    println("в описании со счётом нет. Но и произвольным он не бывает. Нужная жёсткость —")
    println("это тяга, делённая на написанное: λ = F/s − γ. Отсюда и ответ главы 22.")
    println("**λ конечна потому, что конечно написанное**: при 1 %, 0.1 % и 0.01 %")
    @printf("написанного (λ+γ)·s — одно и то же число F (%.3f…%.3f по шести зёрнам), и\n",
            minimum(forces), maximum(forces))
    println("только ноль написанного даёт бесконечную жёсткость. А конечность написанного")
    println("не наша: у точности держания есть пол F·dt/2 — потолок силы, прочитанный с")
    println("другой стороны, — и написанное мельче пола не выполнимо ни при какой")
    println("жёсткости. Оттого одно и то же написанное 1 % при шаге 0.02 держится у " *
            string(counts[end]) * " зёрен")
    println("из шести, а при шаге 0.05 — не больше чем у одного. Точное отношение")
    println("(r₀ = 0) требует и бесконечной жёсткости, и бесконечно мелкого шага: у него нет")
    println("шага, на котором оно стоит.")
    return nothing
end


# Entrain. Курамото: λ и γ — сумма или две величины?
#
# В формуле равновесия строй и затухание стоят суммой:
#
#     x_p = |D_p + γ·r₀_p − p·D₁| / ((λ + γ)·p·ω₁).
#
# Если это так, то и предел у явного шага должен стоять у суммы, а не у λ: множитель,
# которым шаг множит промах, есть 1 − (λ+γ)·dt, и растёт он при (λ+γ)·dt > 2. В
# `tension.jl` записан потолок λ·dt — и там он от суммы неотличим: γ·dt = 0.008.
#
# Здесь сумма разводится. Затухание берётся таким, что произведение γ·dt сравнимо с
# единицей, а одна и та же сумма раскладывается на λ и γ по-разному. Если предел
# стоит у суммы, переход придётся на одно и то же (λ+γ)·dt при всех раскладах; если
# у λ·dt — он уедет вместе с γ.
#
# Мера та же, что в `tension.jl`: промах обертона в долях его собственной частоты, а
# у шага — знак: толчок обертону гаснет или растёт. Только толчок читается разницей
# с ненатолкнутой средой: у промаха есть своё гуляние, и при малом λ оно забивает
# знак.
#
# Итог этого чтения — в журнале: предел явного шага стоит у суммы (λ+γ)·dt, а не у
# λ·dt, как было записано в `tension.jl` (там γ·dt = 0.008, и сумма от λ неотличима).
# Равновесие устроено так же: сумма в знаменателе, а отдельно γ выступает только
# весом написанного промаха r₀. Значит λ в закон входит не сам: строй и затухание
# стоят в нём одним слагаемым.
#
# Запуск:
#
#     julia julia/kuramoto/pair.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const NEAR = 0.02:0.02:3.0   # где искать переход: в единицах λ·dt

"""
    miss(medium)

Промах обертонов — то же число, что читает `x_over` в `tension.jl`: наибольшее из
|ω_p − p·ω₁| / (p·ω₁) по всем вибрациям и обертонам, в долях частоты обертона.
"""
function miss(m::Medium)
    worst = 0.0
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        worst = max(worst, abs(m.omega[i, p] - p * m.omega[i, 1]) / (p * base))
    end
    return worst
end

"""
    chorded(; seed, tuning, damping, link, memory)

Аккорд 1 : 2 : 3 — та же среда, что в `tension.jl`: три моды, полоса 0.10, связь
0.60, написанный промах 1 %. Затухание здесь задаётся затем, что λ и γ придётся
разводить: сумма видна, а слагаемые нет.
"""
function chorded(; seed::Int = 1, tuning::Float64 = 0.0, damping::Float64 = 0.8,
                  link::Float64 = 0.6, memory::Float64 = 1e-3)
    return build(modes = 3, band = 0.1, link = link, tuning = tuning,
                 damping = damping, memory = memory, seed = seed)
end

"""
    advance_step!(medium, seconds, dt)

Прожить средой время при шаге dt — как в `tension.jl`. Сорвавшееся состояние здесь
не сбой, а отметка: фаза ушла внутри шага, и читать уже нечего.
"""
function advance_step!(m::Medium, seconds::Float64, dt::Float64)
    for _ in 1:round(Int, seconds / dt)
        try
            step!(m, dt)
        catch
            fill!(m.omega, Inf)
            fill!(m.theta, Inf)
            return m
        end
        (all(isfinite, m.omega) && all(isfinite, m.theta)) || return m
    end
    return m
end

"""
    growth(lam, dt; damping, seconds, push, seeds)

Во сколько раз вырос толчок обертону за `seconds` секунд. Считается не по промаху
среды (там своё гуляние, и при малом λ оно забивает знак), а по разнице с
ненатолкнутой средой того же зерна: толчок — это δ, и расти он может только сам.
Пара живёт шаг в шаг, как среда и её перестановка в `tension.jl`.
"""
function growth(lam::Float64, dt::Float64; damping::Float64 = 0.8,
                seconds::Float64 = 1.0, push::Float64 = 0.05, seeds = 1:2)
    worst = 0.0
    for s in seeds
        a = chorded(seed = s, tuning = lam, damping = damping)
        b = chorded(seed = s, tuning = lam, damping = damping)
        advance_step!(a, 5.0, dt)
        advance_step!(b, 5.0, dt)
        perturb!(b, 1, push, 2)
        before = maximum(abs.(b.omega .- a.omega))
        # Толчок мог и не дойти: за потолком состояние разъезжается ещё до толчка, и
        # 0.05 к числу вроде 1e34 уже не прибавляется — среды остаются равны. Тогда
        # читать нечего, и это «сорвалась», а не «гаснет».
        before > 0.0 || return NaN
        advance_step!(a, seconds, dt)
        advance_step!(b, seconds, dt)
        # Сорвалось — не «гаснет»: при таком шаге описание кончилось.
        (all(isfinite, a.omega) && all(isfinite, b.omega)) || return NaN
        (all(isfinite, a.theta) && all(isfinite, b.theta)) || return NaN
        worst = max(worst, maximum(abs.(b.omega .- a.omega)) / max(before, 1e-300))
    end
    return worst
end

"Рост к печати: сорвавшееся состояние — это «не сосчитать», а не «гаснет»."
growth_txt(ratio::Float64) = isfinite(ratio) ? @sprintf("×%-9.2e", ratio) : "сорвалась "

"""
    crossing(dt; damping)

Где знак меняется: первое λ·dt, при котором толчок обертону уже растёт. Шаг и
затухание заданы, поэтому точка перехода и переводится потом в единицы суммы —
именно она и сравнивается при разных затуханиях.
"""
function crossing(dt::Float64; damping::Float64 = 0.8)
    for k in NEAR
        growth(k / dt, dt; damping = damping) > 1.0 && return k
    end
    return NaN
end

"""
    drag(medium, i, p)

Тяга связи на моду — тот же член, что в `step!`. Миров внутри у этой среды нет
(`inner = 0`), а значит тяга и есть весь напор: с ней формулу равновесия можно
сверять прямо, не пересказывая шаг.
"""
function drag(m::Medium, i::Int, p::Int)
    d = 0.0
    for j in 1:size(m.omega, 1)
        j == i && continue
        for n in 1:size(m.omega, 2)
            s = overlap(m.omega[j, n] - m.omega[i, p], m.band)
            d += m.coupling[i, j] * s * sin(m.theta[j, n] - m.theta[i, p])
        end
    end
    return d
end


"""
    main()

Прочитать, что правит на шаге и в равновесии: сумма λ+γ или каждое слагаемое своё.

1. Потолок шага: где знак меняется — в единицах λ·dt и в единицах (λ+γ)·dt.
2. Одна сумма, разные расклады: если правит сумма, знак один и тот же.
3. Равновесие: та же сумма в знаменателе — и вес написанного промаха у γ.
"""
function main()
    @printf("λ и γ: сумма или две величины? Вибраций %d, мод 3, полоса 0.10, связь 0.60\n\n",
            N)

    println("--- потолок шага: у суммы (λ+γ)·dt или у λ·dt " * "-"^4)
    println("   Проба: толчок обертону, а рядом — та же среда без толчка. Читается их")
    println("   разница: промах среды сам гуляет, и при малом λ это гуляние забило бы")
    println("   знак. В tension.jl γ·dt = 0.008, и сумма от λ там неотличима; здесь")
    println("   γ·dt ведёт. «Переход» — первое λ·dt, при котором толчок уже растёт;")
    println("   последний столбец — та же точка в единицах суммы: если предел у суммы,")
    println("   он один и тот же при всех затуханиях, а «переход» уезжает сам.")
    for (damp, dt) in ((0.8, 0.01), (0.8, 0.05), (4.0, 0.05), (10.0, 0.05),
                       (20.0, 0.05), (15.0, 0.1))
        k = crossing(dt; damping = damp)
        @printf("   затухание %5.1f   шаг %5.3f   γ·dt %4.2f   переход λ·dt %s   (λ+γ)·dt %s\n",
                damp, dt, damp * dt,
                isnan(k) ? " не нашёлся" : @sprintf("%8.2f", k),
                isnan(k) ? "        —" : @sprintf("%8.2f", k + damp * dt))
    end
    println("   Переход уезжает вместе с затуханием — 2.00 … 0.54, — а в единицах")
    println("   суммы стоит на одном числе: 2.01 … 2.04 при сетке 0.02. Предел у суммы.")

    println("   Одна и та же сумма, разные расклады. Рядом — что из суммы следует:")
    println("   толчок множится за шаг на 1 − (λ+γ)·dt, значит за N шагов — на")
    println("   |1 − (λ+γ)·dt|^N. Если правит сумма, число одно при любом раскладе.")
    for sum_ in (1.6, 2.4)
        for (damp, dt) in ((0.8, 0.05), (10.0, 0.05), (20.0, 0.05))
            lam = (sum_ - damp * dt) / dt
            steps = round(Int, 1.0 / dt)
            @printf("   (λ+γ)·dt %4.2f   затухание %5.1f   γ·dt %4.2f   λ·dt %4.2f   λ %7.1f   измерено %s  предсказано %s\n",
                    sum_, damp, damp * dt, lam * dt, lam,
                    growth_txt(growth(lam, dt; damping = damp)),
                    growth_txt(abs(1 - sum_)^steps))
        end
    end
    println("   При одном (λ+γ)·dt 2.4 три расклада дают одно число — против")
    println("   предсказанного |1 − 2.4|²⁰ = ×8.37e+02, — хотя λ·dt в них 2.36, 1.90")
    println("   и 1.40: по чтению «λ·dt» последний обязан был гаснуть, он растёт.")
    println("   Ниже предела числа расходятся с предсказанным в разы: там гасит не")
    println("   только строй — своя скорость есть и у связи, — но от расклада они не")
    println("   зависят: одно число на одну сумму.")
    println("   За потолком проба теряет и сам толчок — но не сразу, а там, где к")
    println("   моменту толчка промах уже так велик, что толчок 0.05 к нему не")
    println("   прибавляется: среды остаются побитово равны, и строка выше скажет")
    println("   «сорвалась». Шаг решает, где это начинается (сумма 2.4):")
    for (damp, dt) in ((0.8, 0.05), (10.0, 0.05), (20.0, 0.05), (25.0, 0.02))
        lam = (2.4 - damp * dt) / dt
        a = chorded(seed = 1, tuning = lam, damping = damp)
        b = chorded(seed = 1, tuning = lam, damping = damp)
        advance_step!(a, 5.0, dt)
        advance_step!(b, 5.0, dt)
        scale = miss(a)
        perturb!(b, 1, 0.05, 2)
        reached = maximum(abs.(b.omega .- a.omega)) > 0.0
        @printf("   затухание %5.1f  шаг %5.3f   промах к толчку %9.2e   толчок дошёл: %s\n",
                damp, dt, scale, reached ? "да" : "нет")
    end
    println("   За потолком состояние разъезжается само: к толчку промах уже 1e12 —")
    println("   аккорда нет, и мера говорит «сорвалась», а не выдаёт рост. При шаге")
    println("   0.05 толчок 0.05 всё же доходит — частоты ещё порядка единицы; при")
    println("   0.02 разъезжаются и сами частоты (1e34), и 0.05 в них не прибавляется.")
    println("   Это и есть «читать нечего», названное числом.")

    println("\n--- равновесие: сумма в знаменателе, γ — вес написанного промаха " * "-"^2)
    println("   Одна сумма (λ+γ) при разных раскладах, и против чисел — формула")
    println("   равновесия из tension.jl:")
    println("      промах = |D_p + γ·r₀_p − p·D₁| / ((λ+γ)·p·ω₁).")
    println("   Знаменатель у всех раскладов один, а числитель нет: γ стоит отдельно")
    println("   ещё и как вес написанного промаха r₀ — единственное место, где он не")
    println("   в сумме.")
    for (lam, damp) in ((16.0, 0.8), (8.8, 8.0), (15.2, 1.6), (16.8, 0.0))
        worst, pred = 0.0, 0.0
        for s in SEEDS
            m = chorded(seed = s, tuning = lam, damping = damp)
            advance_step!(m, 60.0, DT)
            xi, xp, x = 1, 2, 0.0
            for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
                base = abs(m.omega[i, 1])
                base == 0.0 && continue
                v = abs(m.omega[i, p] - p * m.omega[i, 1]) / (p * base)
                v > x && ((xi, xp, x) = (i, p, v))
            end
            base = abs(m.omega[xi, 1])
            r0 = m.omega0[xi, xp] - xp * m.omega0[xi, 1]
            held = abs(drag(m, xi, xp) + damp * r0 - xp * drag(m, xi, 1)) /
                   ((lam + damp) * xp * base)
            worst = max(worst, x)
            pred = max(pred, held)
        end
        @printf("   λ %5.1f  γ %4.1f  (λ+γ) %5.1f   измерено %8.6f   по формуле %8.6f\n",
                lam, damp, lam + damp, worst, pred)
    end
    println("   Формула держит все расклады одной суммы: знаменатель (λ+γ) у них")
    println("   один, а числа разные — 0.0223 против 0.0268 при одном (λ+γ) = 16.8.")
    println("   Разное в них — вес написанного промаха γ·r₀: это единственное место,")
    println("   где γ стоит отдельно от λ. И видно, за что он там отвечает: за то, что")
    println("   было написано, а не за силу строя. При γ = 0 формула идёт чуть впереди")
    println("   (0.0146 против 0.0150) — без затухания равновесию не на чем стоять.")

    println("\nИтог: λ входит в закон только суммой с γ. Потолок явного шага стоит у")
    println("произведения (λ+γ)·dt — на 2.0 при затухании от 0.8 до 20 и шаге от 0.01")
    println("до 0.1, тогда как λ·dt при этом уезжает от 2.0 до 0.54. Равновесие того же")
    println("устройства: при одной сумме знаменатель один, и промах сходится по формуле")
    println("при любом раскладе. Отдельно γ стоит только весом написанного промаха.")
    println("Значит «сколько нужно строя» без «сколько в среде затухания» не читается:")
    println("строй и затухание — одно слагаемое на двоих, и записывать потолок через λ")
    println("можно лишь там, где γ·dt мал настолько, что сумма от λ неотличима.")

    return nothing
end


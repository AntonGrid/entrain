Прочитать перевес: из чего он состоит и почему конечен.

1. Тяга у мод разная: D = D_p − p·D₁ — то, с чем спорит перевес.
2. Без перевеса (λ = 0): тяга сбивает промах на D/γ — цена без строя.
3. Перевес в стоячем: сила λ·r₀ против тяги D; где промах стоит на написанном.
4. Тот же перевес в возврате: две скорости и доля формы λ/(λ+γ).

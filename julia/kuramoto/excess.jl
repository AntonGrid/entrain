# Entrain. Курамото: перевес — из чего он состоит и почему конечен.
#
# λ читается разностью скоростей (`rates.jl`): у промаха обертона множитель шага
# 1 − (λ+γ)·dt, у самой основной частоты — 1 − γ·dt. Читается — но не выведен:
# остаётся перевес, сам вопрос, почему промах спешит быстрее основной.
#
# Здесь он читается как сила. На промахе r = ω_p − p·ω₁ стоят две возвращающие
# силы: строй тянет промах к точному отношению (r → 0), затухание — к написанному
# (r → r₀). Спор их закрывается равновесием
#
#     D = λ·r + γ·(r − r₀),    D = D_p − p·D₁,
#
# где D_p — тяга связи на моду, тот же член, что в шаге. Отсюда две картины одного
# числа — в возврате и в стоячем:
#
#     возврат отклонения:  r′ = r + dt·((D − λ·r₀) − (λ+γ)·(r − r₀))
#     возврат у основной:  ω₁′ = ω₁ + dt·(D₁ − γ·(ω₁ − ω₀₁))     — строя нет вовсе
#     стоячее:             отклонение от написанного  r − r₀ = (D − λ·r₀)/(λ+γ)
#
# Тяга у мод разная: D_p ≠ p·D₁, потому что тянут фазы, а не номера мод, — и
# именно эту разницу перевес и уносит. Без строя она сбивает промах на D/γ; при
# λ = D/r₀ промах стоит там, где написан; дальше — идёт к точному отношению.
# Затухание в стоячем своё держит только отклонением γ·(r − r₀), а написанное
# держит один перевес силой λ·r₀. Отсюда и две скорости у одной среды.
#
# Читается всё это без написанных чисел, кроме самих λ и γ: скорости — толчком
# (`rates.jl`), тяга — тем же членом, что в шаге (`drag`), написанный промах —
# своими частотами описания.
#
# Итог этого чтения — в конце сцены; в журнал он не внесён.
#
# Запуск:
#
#     julia julia/kuramoto/excess.jl

include(joinpath(@__DIR__, "basic.jl"))

const SEEDS = 1:6
const WINDOW = 4        # на каком окне читаются скорости: шагов — как в rates.jl
const PUSH = 0.02       # толчок в основную частоту вибрации 1

"""
    drag(medium, i, p)

Тяга связи на моду — тот же член, что в `step!`, без строя и затухания. Миров
внутри у сред этой сцены нет (`inner = 0`), а значит тяга и есть весь напор.
"""
function drag(m::Medium, i::Int, p::Int)
    d = 0.0
    for j in 1:size(m.omega, 1)
        j == i && continue
        for n in 1:size(m.omega, 2)
            s = overlap(m.omega[j, n] - m.omega[i, p], m.band)
            d += m.coupling[i, j] * s * sin(m.theta[j, n] - m.theta[i, p])
        end
    end
    return d
end

"""
    x_over(medium)

Промах обертонов: наибольшее из |ω_p − p·ω₁| / (p·ω₁) — та же мера, что в
`tension.jl`. Возвращается и место — (вибрация, обёртон).
"""
function x_over(m::Medium)
    worst, at = 0.0, (1, 1)
    for i in 1:size(m.omega, 1), p in 2:size(m.omega, 2)
        base = abs(m.omega[i, 1])
        base == 0.0 && continue
        x = abs(m.omega[i, p] - p * m.omega[i, 1]) / (p * base)
        x > worst && ((worst, at) = (x, (i, p)))
    end
    return worst, at
end

"Написанный промах r₀ = ω₀_p − p·ω₀₁ — то, чем среда была написана."
written(m::Medium, i::Int, p::Int) = m.omega0[i, p] - p * m.omega0[i, 1]

"Разность тяг D = D_p − p·D₁ — то, чем тяга уводит промах."
pull(m::Medium, i::Int, p::Int) = drag(m, i, p) - p * drag(m, i, 1)


"""
    chorded(; seed, tuning, damping, link, memory)

Аккорд 1 : 2 : 3 — та же среда, что в `pair.jl` и `rates.jl`: три моды, полоса
0.10, связь 0.60, написанный промах 1 %.
"""
function chorded(; seed::Int = 1, tuning::Float64 = 0.0, damping::Float64 = 0.8,
                  link::Float64 = 0.6, memory::Float64 = 1e-3)
    return build(modes = 3, band = 0.1, link = link, tuning = tuning,
                 damping = damping, memory = memory, seed = seed)
end

"""
    exact(; seed, tuning, damping, link, memory)

Та же среда, но аккорд написан точно: ω₀_p = p·ω₀₁, промах r₀ = 0. Контроль к
«из чего состоит перевес»: если спор идёт с написанным, то там, где написанного
нет, картина должна быть проще.
"""
function exact(; seed::Int = 1, tuning::Float64 = 0.0, damping::Float64 = 0.8,
                link::Float64 = 0.6, memory::Float64 = 1e-3)
    m = chorded(seed = seed, tuning = tuning, damping = damping, link = link,
                memory = memory)
    for i in 1:size(m.omega0, 1), p in 2:size(m.omega0, 2)
        m.omega0[i, p] = p * m.omega0[i, 1]
    end
    m.omega .= m.omega0
    return m
end

"""
    advance_step!(medium, seconds, dt)

Прожить средой время при шаге dt — как в `rates.jl`. Сорвавшееся состояние здесь
не сбой, а отметка: фаза ушла внутри шага, и читать уже нечего.
"""
function advance_step!(m::Medium, seconds::Float64, dt::Float64)
    for _ in 1:round(Int, seconds / dt)
        try
            step!(m, dt)
        catch
            fill!(m.omega, Inf)
            fill!(m.theta, Inf)
            return m
        end
        (all(isfinite, m.omega) && all(isfinite, m.theta)) || return m
    end
    return m
end

"""
    measured(lam, damp, dt, win, push_mode; f, ...)

Сколько за шаг даёт величина `f` после толчка на моду `push_mode` вибрации 1 —
то же чтение скоростей, что в `rates.jl`: среднее геометрическое по зёрнам от
(после / до)^(1/окно), считанное по разнице с ненатолкнутой средой того же зерна.
"""
function measured(lam::Float64, damp::Float64, dt::Float64, win::Int, push_mode::Int;
                  seeds = SEEDS, memory::Float64 = 1e-3, push::Float64 = PUSH,
                  f, seconds::Float64 = 5.0)
    logs = Float64[]
    for s in seeds
        a = chorded(seed = s, tuning = lam, damping = damp, memory = memory)
        b = chorded(seed = s, tuning = lam, damping = damp, memory = memory)
        advance_step!(a, seconds, dt)
        advance_step!(b, seconds, dt)
        perturb!(b, 1, push, push_mode)
        before = f(b) - f(a)
        before != 0.0 || return NaN
        advance_step!(a, win * dt, dt)
        advance_step!(b, win * dt, dt)
        (all(isfinite, a.omega) && all(isfinite, b.omega)) || return NaN
        after = f(b) - f(a)
        after != 0.0 || return NaN
        push!(logs, log(abs(after / before)) / win)
    end
    return exp(sum(logs) / length(logs))
end

"Промах вибрации 1 по обёртону 2 и её основная частота — величины того же опыта."
miss_of(m::Medium) = m.omega[1, 2] - 2 * m.omega[1, 1]
own_of(m::Medium) = m.omega[1, 1]

"""
    settled(; seconds, kwargs...)

Среда, прожившая `seconds` секунд: один и тот же шаг чтения во всех строках.
"""
function settled(; seconds::Float64 = 60.0, dt::Float64 = DT, kwargs...)
    m = chorded(; kwargs...)
    advance_step!(m, seconds, dt)
    return m
end


"""

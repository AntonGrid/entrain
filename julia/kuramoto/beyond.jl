# Entrain. Граница N: десять вибраций или тридцать.
#
# Тот же прогон, что `consistency.jl`, но вибраций в среде тридцать. Меняется один
# параметр: N. Шаг (0.01 с), полоса, связь (0.6 / N на пару, чтобы полная тяга
# среды осталась прежней), затухание, память, написанный промах, зёрна и пороги
# — те же: 86 утверждений и те же допуски. Пороги места берутся от степени, а не
# от N (`PLACE_FLOOR = 5` и `SHORT_PLACE_SPREAD = 10` при `DEGREE = 0`), поэтому
# прогон при N = 30 сверяется с полным графом, а не с городом: тридцать вибраций
# — это тот же полный граф, только крупнее.
#
# Критерий объявлен до прогона: поломка — любой из тех же 86 пунктов, который
# печатает «НЕ СОШЛОСЬ» при тех же допусках и порогах. Единственная правка
# утверждения — разбиение десяти вибраций на части в строке «наложение: целое =
# взвешенная сумма частей» — сделана по N, а не по десяти; при N = 10 она даёт
# те же массивы до бита. Других правок нет.
#
# Итог прогона 2026-10-20 (N = 30): 86 из 86, «НЕ СОШЛОСЬ» нет ни одного. Числа
# тех пунктов, о которых шла речь в прежних записях: место 8.79 у 1-й вибрации и
# 15.2 у 5-й при полу 5; разброс короткой памяти 2.8e+06 при полу 10; отзвук
# 12.5 при полу 5; рельеф тает с ошибкой 6.9e-04 при пороге 2e-2; стоячая доля
# 4.8e-03 при пороге 2e-2.
#
# Время прогона (Julia 1.10.12, один поток, N = 30, 86 утверждений): 31.8 мин
# (1907 с; процессорного времени 1904 с — весь прогон на одном ядре). Для
# сравнения: `consistency.jl` при N = 10 — 5.8 мин, `city.jl` при N = 100, z = 4 —
# 22.6 мин. Это ночная сверка, а не единичный тест; в CI её место — отдельный
# долгий шаг, а не короткий.
#
# Запись 2026-10-19 (81 из 86, коммит ec2b161) — история, а не текущее состояние
# набора. Она снята на другой цели памяти: тогда среда писала `link + N₀·cos` без
# деления на K, и при N = 30 те же два пункта дали 4.09 и 0.57. Коммит 460bbe4
# сменил цель на `(link + N₀·cos)/K`, и место стало 8.79 — промах был не в записи
# места и не в пороге, а в цели, которую среда писала. Остальные три пункта той
# записи разобраны сценами и переписаны в 7b71fe4: «похожесть рельефа» стала
# рангом места (`relief_site_rank`), «рельеф тает» — сценой `fade_scan.jl`
# (δ = u + h, u тает по e^(−εT)), «стоячая доля» — сценой `standing_scan.jl`
# (e = s·|q|/|D|, по N немонотонно). Прежние числа оставлены здесь, чтобы видно
# было, чем запись отличалась, а не чтобы их перепроверять.
